#include <ultra64.h>
#include "conker/math.h"


void math_mtxAffineInverse(MtxF m, MtxF out) {
    f32 det;

    det = 0.0f;
    det += m[0][0] * m[1][1] * m[2][2];
    det += m[0][1] * m[1][2] * m[2][0];
    det += m[0][2] * m[1][0] * m[2][1];
    det -= m[0][2] * m[1][1] * m[2][0];
    det -= m[0][1] * m[1][0] * m[2][2];
    det -= m[0][0] * m[1][2] * m[2][1];
    det = 1.0f / det;
    out[0][0] = (m[1][1] * m[2][2] - m[1][2] * m[2][1]) * det;
    out[1][0] = (m[1][2] * m[2][0] - m[1][0] * m[2][2]) * det;
    out[2][0] = (m[1][0] * m[2][1] - m[1][1] * m[2][0]) * det;
    out[0][1] = (m[0][2] * m[2][1] - m[0][1] * m[2][2]) * det;
    out[1][1] = (m[0][0] * m[2][2] - m[0][2] * m[2][0]) * det;
    out[2][1] = (m[0][1] * m[2][0] - m[0][0] * m[2][1]) * det;
    out[0][2] = (m[0][1] * m[1][2] - m[0][2] * m[1][1]) * det;
    out[1][2] = (m[0][2] * m[1][0] - m[0][0] * m[1][2]) * det;
    out[2][2] = (m[0][0] * m[1][1] - m[0][1] * m[1][0]) * det;
    out[3][0] = -(m[3][0] * out[0][0] + m[3][1] * out[1][0] + m[3][2] * out[2][0]);
    out[3][1] = -(m[3][0] * out[0][1] + m[3][1] * out[1][1] + m[3][2] * out[2][1]);
    out[3][2] = -(m[3][0] * out[0][2] + m[3][1] * out[1][2] + m[3][2] * out[2][2]);
    out[0][3] = 0.0f;
    out[1][3] = 0.0f;
    out[2][3] = 0.0f;
    out[3][3] = 1.0f;
}
